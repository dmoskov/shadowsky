// Design-token ratchet for the mobile app. Counts hardcoded color literals
// (hex and rgb/rgba) per file under src/ and app/ and compares against the
// checked-in baseline. New violations fail CI; counts may only go down.
// Colors belong in the theme (src/constants/theme.ts via useTheme()) — see
// docs/DESIGN.md at the repo root.
//
// Usage (from mobile/):
//   node scripts/check-design-tokens.mjs            # check against baseline
//   node scripts/check-design-tokens.mjs --update   # rewrite baseline (after
//                                                   # intentional cleanup)

import { readFileSync, writeFileSync, readdirSync, statSync, existsSync } from "node:fs";
import { join, relative, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const mobileRoot = join(dirname(fileURLToPath(import.meta.url)), "..");
const baselinePath = join(mobileRoot, "scripts", "design-tokens-baseline.txt");

const COLOR_LITERAL = /#[0-9a-fA-F]{3,8}\b|rgba?\(/g;
const SKIP = /__tests__|\.test\.|constants\/generated\//;

function* walk(dir) {
  for (const entry of readdirSync(dir)) {
    const p = join(dir, entry);
    if (statSync(p).isDirectory()) yield* walk(p);
    else if (/\.(tsx|ts)$/.test(entry)) yield p;
  }
}

const counts = new Map();
for (const root of ["src", "app"]) {
  for (const file of walk(join(mobileRoot, root))) {
    const rel = relative(mobileRoot, file);
    if (SKIP.test(rel)) continue;
    let n = 0;
    for (const line of readFileSync(file, "utf8").split("\n")) {
      const code = line.replace(/\/\/.*$/, "");
      n += [...code.matchAll(COLOR_LITERAL)].length;
    }
    if (n > 0) counts.set(rel, n);
  }
}

if (process.argv.includes("--update")) {
  const lines = [...counts.entries()]
    .sort(([a], [b]) => a.localeCompare(b))
    .map(([file, n]) => `${file} ${n}`);
  writeFileSync(
    baselinePath,
    `# Hardcoded color-literal counts, per file. Generated by\n# \`node scripts/check-design-tokens.mjs --update\`. Counts may only go down.\n${lines.join("\n")}\n`,
  );
  console.log(`Baseline updated: ${counts.size} files.`);
  process.exit(0);
}

const baseline = new Map();
if (existsSync(baselinePath)) {
  for (const line of readFileSync(baselinePath, "utf8").split("\n")) {
    const m = line.trim().match(/^(\S+) (\d+)$/);
    if (m) baseline.set(m[1], Number(m[2]));
  }
}

let failed = false;
for (const [file, n] of [...counts.entries()].sort()) {
  const allowed = baseline.get(file) ?? 0;
  if (n > allowed) {
    failed = true;
    console.error(
      `${file}: ${n} hardcoded color literal(s), baseline allows ${allowed}`,
    );
  }
}

if (failed) {
  console.error(
    "\nUse theme colors via useTheme()/createStyles(colors) instead of literals (docs/DESIGN.md). If a literal is genuinely intentional (media chrome, dynamic scrims), run `node scripts/check-design-tokens.mjs --update` and justify the baseline change in your PR.",
  );
  process.exit(1);
}
console.log(`Design-token ratchet clean (${counts.size} baselined files).`);

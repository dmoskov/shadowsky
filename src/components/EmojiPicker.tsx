const STORAGE_KEY = "bsky-recent-emojis";
const MAX_RECENT_EMOJIS = 30;

// Grid virtualization constants
const COLUMN_COUNT = 8;
const CELL_SIZE = 44; // Size of each emoji cell in pixels (text-2xl + p-2 padding)

// Cell props type for react-window v2 Grid
interface EmojiCellProps {
  emojis: string[];
  onSelect: (emoji: string) => void;
}

// Cell component for react-window v2 Grid
function EmojiCell({
  columnIndex,
  rowIndex,
  style,
  emojis,
  onSelect,
}: {
  columnIndex: number;
  rowIndex: number;
  style: CSSProperties;
  emojis: string[];
  onSelect: (emoji: string) => void;
}) {
  const index = rowIndex * COLUMN_COUNT + columnIndex;
  const emoji = emojis[index];

  if (!emoji) return <div style={style} />;

  return (
    <div style={style}>
      <button
        onClick={() => onSelect(emoji)}
        className="flex h-full w-full items-center justify-center rounded text-2xl hover:bg-gray-100"
        style={{
          background: "transparent",
          transition: "background 0.2s",
        }}
      >
        {emoji}
      </button>
    </div>
  );
}

export function EmojiPicker({ onSelectEmoji, onClose }: EmojiPickerProps) {
  const [selectedCategory, setSelectedCategory] = useState("smileys");
  const [searchTerm, setSearchTerm] = useState("");
  const debouncedSearchTerm = useDelayedValue(searchTerm, 150);
  const [recentEmojis, setRecentEmojis] = useState<string[]>([]);
  const searchInputRef = useRef<HTMLInputElement>(null);

  // Load recent emojis on mount
  useEffect(() => {
    const stored = localStorage.getItem(STORAGE_KEY);
    if (stored) {
      try {
        const emojis = JSON.parse(stored);
        setRecentEmojis(emojis);
        EMOJI_CATEGORIES.recent.emojis = emojis;
      } catch (_e) {
        console.error("Error loading recent emojis:", _e);
      }
    }
  }, []);

  const handleSelectEmoji = (emoji: string) => {
    // Add to recent emojis
    const newRecent = [emoji, ...recentEmojis.filter((e) => e !== emoji)].slice(
      0,
      MAX_RECENT_EMOJIS,
    );
    setRecentEmojis(newRecent);
    EMOJI_CATEGORIES.recent.emojis = newRecent;
    localStorage.setItem(STORAGE_KEY, JSON.stringify(newRecent));

    onSelectEmoji(emoji);
  };

  const searchResults = useMemo(() => {
    if (!debouncedSearchTerm) return [];

    const results: string[] = [];
    const search = debouncedSearchTerm.toLowerCase();

    Object.values(EMOJI_CATEGORIES).forEach((category) => {
      category.emojis.forEach((emoji) => {
        if (emoji.toLowerCase().includes(search)) {
          results.push(emoji);
        }
      });
    });

    return results;
  }, [debouncedSearchTerm]);

  const displayEmojis = debouncedSearchTerm
    ? searchResults
    : selectedCategory === "recent" && recentEmojis.length === 0
      ? EMOJI_CATEGORIES.smileys.emojis
      : EMOJI_CATEGORIES[selectedCategory as keyof typeof EMOJI_CATEGORIES]
          .emojis;

  // Calculate grid dimensions
  const rowCount = Math.ceil(displayEmojis.length / COLUMN_COUNT);
  const gridContainerRef = useRef<HTMLDivElement>(null);
  const [gridHeight, setGridHeight] = useState(300);

  // Measure container height for the virtualized grid
  useEffect(() => {
    const container = gridContainerRef.current;
    if (container) {
      const observer = new ResizeObserver((entries) => {
        const entry = entries[0];
        if (entry) {
          setGridHeight(entry.contentRect.height);
        }
      });
      observer.observe(container);
      return () => observer.disconnect();
    }
  }, []);

  return (
    <div
      className="fixed inset-0 z-50 flex items-center justify-center p-4"
      style={{ background: "rgba(0, 0, 0, 0.5)" }}
    >
      <div
        className="flex max-h-[80vh] w-full max-w-md flex-col overflow-hidden rounded-lg"
        style={{ background: "var(--bsky-bg-primary)" }}
      >
        <div
          className="border-b p-4"
          style={{ borderColor: "var(--bsky-border-primary)" }}
        >
          <div className="mb-3 flex items-center justify-between">
            <h3
              className="text-lg font-semibold"
              style={{ color: "var(--bsky-text-primary)" }}
            >
              Choose an Emoji
            </h3>
            <button
              onClick={onClose}
              className="touch-target-icon rounded hover:bg-gray-100 dark:hover:bg-gray-800"
              aria-label="Close"
            >
              <X size={20} />
            </button>
          </div>

          <div className="relative">
            <Search
              className="absolute left-3 top-1/2 -translate-y-1/2 transform"
              size={20}
              style={{ color: "var(--bsky-text-tertiary)" }}
            />
            <input
              ref={searchInputRef}
              type="text"
              placeholder="Search emojis..."
              value={searchTerm}
              onChange={(e) => setSearchTerm(e.target.value)}
              className="w-full rounded-lg py-2 pl-10 pr-4"
              style={{
                background: "var(--bsky-bg-secondary)",
                border: "1px solid var(--bsky-border-primary)",
                color: "var(--bsky-text-primary)",
                outline: "none",
              }}
              onFocus={(e) =>
                (e.target.style.borderColor = "var(--bsky-primary)")
              }
              onBlur={(e) =>
                (e.target.style.borderColor = "var(--bsky-border-primary)")
              }
              autoFocus
            />
          </div>
        </div>

        {!searchTerm && (
          <div
            className="flex overflow-x-auto border-b"
            style={{ borderColor: "var(--bsky-border-primary)" }}
          >
            {Object.entries(EMOJI_CATEGORIES).map(([key, category]) => {
              if (key === "recent" && recentEmojis.length === 0) return null;

              const Icon = category.icon;
              return (
                <button
                  key={key}
                  onClick={() => setSelectedCategory(key)}
                  className={`flex-shrink-0 p-3 ${selectedCategory === key ? "border-b-2" : ""}`}
                  style={{
                    borderColor:
                      selectedCategory === key
                        ? "var(--bsky-primary)"
                        : "transparent",
                    color:
                      selectedCategory === key
                        ? "var(--bsky-primary)"
                        : "var(--bsky-text-secondary)",
                  }}
                  title={category.name}
                >
                  <Icon size={20} />
                </button>
              );
            })}
          </div>
        )}

        <div ref={gridContainerRef} className="flex-1 overflow-hidden p-2">
          {displayEmojis.length === 0 && debouncedSearchTerm && (
            <div className="py-8 text-center">
              <p style={{ color: "var(--bsky-text-secondary)" }}>
                No emojis found
              </p>
            </div>
          )}

          {displayEmojis.length > 0 && (
            <Grid<EmojiCellProps>
              cellComponent={EmojiCell}
              cellProps={{ emojis: displayEmojis, onSelect: handleSelectEmoji }}
              columnCount={COLUMN_COUNT}
              columnWidth={CELL_SIZE}
              rowCount={rowCount}
              rowHeight={CELL_SIZE}
              defaultHeight={gridHeight}
              style={{
                margin: "0 auto",
                width: COLUMN_COUNT * CELL_SIZE,
                height: gridHeight,
              }}
            />
          )}
        </div>
      </div>
    </div>
  );
}
